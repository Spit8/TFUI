import type { Screen, TfuiProject } from "../model/types";
import { emitNumber, emitString } from "./luaEmit";
import type { GeneratedFile } from "./types";

export function genRes(
  project: TfuiProject,
  screen: Screen,
): GeneratedFile | null {
  if (screen.kind !== "plugin" || !screen.plugin) return null;

  const modId = project.mod.modId;
  const guiDir = project.mod.guiDir.replace(/\\/g, "/").replace(/^\/+|\/+$/g, "");
  const pluginRecipe = screen.plugin.pluginName;
  const filePath = `${modId}::/${guiDir}/${screen.fileBase}.script@${pluginRecipe}`;

  const content = [
    `-- Generated by TFUI - Transport Fever 3 UI Editor — fichier régénéré, ne pas modifier`,
    `function data()`,
    `\treturn {`,
    `\t\ttype = "react-plugin ::MainModButtonAreaExtension",`,
    `\t\tdata = {`,
    `\t\t\tfilePath = ${emitString(filePath)},`,
    `\t\t\torder = ${emitNumber(screen.plugin.order)},`,
    `\t\t},`,
    `\t}`,
    `end`,
    ``,
  ].join("\n");

  return {
    path: `${screen.fileBase}_button.res.lua`,
    content,
    sourceMap: [],
    kind: "res",
    screenId: screen.id,
  };
}
