import { describe, expect, it } from "vitest";
import { createEmptyProject, createNode } from "../model/factory";
import { insertNode, setNodeProp } from "../model/treeOps";
import { generateProject } from "./generate";
import {
  appendHandlerStubs,
  genHandlersFile,
  handlersModulePath,
  missingHandlers,
} from "./handlersFile";

function projectWithHandler(fn: string) {
  let project = createEmptyProject({ modId: "tfui_example" });
  project = {
    ...project,
    screens: project.screens.map((s, i) =>
      i === 0 ? { ...s, fileBase: "main_gui", recipeName: "MainWindow" } : s,
    ),
  };
  const screen = project.screens[0]!;
  const box = createNode("BoxLayout");
  project = insertNode(project, screen.id, screen.root.id, "content", box);
  const button = createNode("Button");
  project = insertNode(project, screen.id, box.id, "children", button);
  return setNodeProp(project, button.id, "onClick", { kind: "handler", fn });
}

describe("fichier handlers de l’utilisateur", () => {
  it("le script charge le module du mod et référence handlers.<nom>", () => {
    const project = projectWithHandler("onApplyClick");
    const script = generateProject(project).find((f) => f.kind === "script")!;
    const path = handlersModulePath("tfui_example", project.mod.guiDir, "main_gui");
    expect(path).toMatch(/^tfui_example::\/.*main_gui\.handlers\.lua$/);
    expect(script.content).toContain(`local handlers = ug_require "${path}"`);
    expect(script.content).toContain("onClick = handlers.onApplyClick,");
    expect(script.content).not.toContain("@tfui:begin");
    expect(script.handlers).toEqual(["onApplyClick"]);
  });

  it("sans handler, pas de require", () => {
    let project = createEmptyProject({ modId: "tfui_example" });
    project = { ...project };
    for (const f of generateProject(project).filter((x) => x.kind === "script")) {
      expect(f.content).not.toContain("local handlers");
    }
  });

  it("stubs initiaux, puis détection des manquants et ajout avant return", () => {
    const content = genHandlersFile({ fileBase: "main_gui", handlerNames: ["onA"] });
    expect(content).toContain("function handlers.onA()");
    expect(content.trimEnd().endsWith("return handlers")).toBe(true);
    expect(missingHandlers(content, ["onA", "onB"])).toEqual(["onB"]);
    const added = appendHandlerStubs(content, ["onB"])!;
    expect(missingHandlers(added, ["onA", "onB"])).toEqual([]);
    expect(added.indexOf("handlers.onB")).toBeLessThan(added.lastIndexOf("return handlers"));
    expect(added.startsWith(content.split("return handlers")[0]!)).toBe(true);
    expect(appendHandlerStubs("print(1)", ["x"])).toBeNull();
  });

  it("migration : l’ancienne région est reprise et ses fonctions exposées", () => {
    const legacy = `local function onA()\n\tprint(builtin.type)\nend\n\nlocal helper = 1`;
    const content = genHandlersFile({ fileBase: "main_gui", handlerNames: ["onA", "onB"], legacyRegion: legacy });
    expect(content).toContain(`local builtin = ug_require "::/gui/main/builtin.lua"`);
    expect(content).toContain("local helper = 1");
    expect(content).toContain("handlers.onA = onA");
    expect(content).toContain("function handlers.onB()");
    expect(missingHandlers(content, ["onA", "onB"])).toEqual([]);
  });

  it("l’en-tête ne ressemble pas à un fichier généré (jamais supprimé ni écrasé)", () => {
    expect(genHandlersFile({ fileBase: "x", handlerNames: ["a"] })).not.toContain("Generated by");
  });
});
