import { describe, expect, it } from "vitest";
import { createEmptyProject } from "../model/factory";
import { genCss } from "./genCss";

describe("genCss header", () => {
  it("émet l’en-tête Generated by TFUI - Transport Fever 3 UI Editor", () => {
    const project = createEmptyProject({ modId: "m" });
    const file = genCss(project, project.screens[0]);
    expect(file.content.startsWith("-- Generated by TFUI - Transport Fever 3 UI Editor")).toBe(
      true,
    );
  });
});
