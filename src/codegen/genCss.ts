import {
  emittedSelectors,
  sharedRules,
  STYLE_STATES,
} from "../model/elementStyle";
import type {
  Screen,
  StyleProps,
  StyleRule,
  TfuiProject,
  UiNode,
} from "../model/types";
import { isPaletteColor, isPaletteName } from "../model/paletteColor";
import {
  emitArray,
  emitBoolean,
  emitNumber,
  emitPaletteColor,
  emitString,
  PALETTE_ACCESS,
} from "./luaEmit";
import type { GeneratedFile } from "./types";

function emitCssProps(props: StyleProps): string {
  const entries: string[] = [];
  for (const [key, raw] of Object.entries(props)) {
    if (raw === undefined) continue;
    if (isPaletteColor(raw) && isPaletteName(raw.name)) {
      entries.push(`\t\t${key} = ${emitPaletteColor(raw.name, raw.alpha, "colorDefault")},`);
    } else if (Array.isArray(raw) && raw.every((n) => typeof n === "number")) {
      entries.push(`\t\t${key} = ${emitArray(raw as number[])},`);
    } else if (typeof raw === "number") {
      entries.push(`\t\t${key} = ${emitNumber(raw)},`);
    } else if (typeof raw === "boolean") {
      entries.push(`\t\t${key} = ${emitBoolean(raw)},`);
    } else if (typeof raw === "string") {
      entries.push(`\t\t${key} = ${emitString(raw)},`);
    }
  }
  if (entries.length === 0) return "{}";
  return `{\n${entries.join("\n")}\n\t}`;
}

/** Règle scopée à une recipe d’écran (`R::RecipeName …`). */
export function isCssRuleScoped(rule: StyleRule): boolean {
  return /R::[A-Za-z_][\w]*/.test(rule.selector);
}

function screenNodeIds(node: UiNode, into: Set<string>): Set<string> {
  into.add(node.id);
  for (const children of Object.values(node.slots)) {
    for (const c of children) screenNodeIds(c, into);
  }
  return into;
}

const STATE_ORDER = [undefined, ...STYLE_STATES];

/** Règles d’un écran avec leur sélecteur émis. */
function rulesForScreen(
  project: TfuiProject,
  screen: Screen,
): { rule: StyleRule; selector: string }[] {
  const shared = sharedRules(project);
  const scoped = shared.filter((r) =>
    r.selector.includes(`R::${screen.recipeName}`),
  );
  // R4(a) : règles non scopées émises dans chaque .css.lua
  const unscoped = shared.filter((r) => !isCssRuleScoped(r));
  // Style par élément : après les classes partagées pour l’emporter, Normal
  // puis les états.
  const ids = screenNodeIds(screen.root, new Set());
  const element = project.styleRules
    .filter((r) => r.ownerNodeId && ids.has(r.ownerNodeId))
    .filter((r) => Object.keys(r.props).length > 0)
    .sort((a, b) => STATE_ORDER.indexOf(a.state) - STATE_ORDER.indexOf(b.state));
  return [...scoped, ...unscoped, ...element].flatMap((rule) =>
    emittedSelectors(rule, screen).map((selector) => ({ rule, selector })),
  );
}

export function genCss(
  project: TfuiProject,
  screensInput: Screen | Screen[],
): GeneratedFile {
  const screens = Array.isArray(screensInput) ? screensInput : [screensInput];
  const fileBase = screens[0]?.fileBase ?? "main_gui";
  const seenIds = new Set<string>();
  const rules: { rule: StyleRule; selector: string }[] = [];
  for (const screen of screens) {
    for (const entry of rulesForScreen(project, screen)) {
      // R4(b) : dédup par id (une règle d’élément peut avoir plusieurs sélecteurs)
      const key = `${entry.rule.id}\u0000${entry.selector}`;
      if (seenIds.has(key)) continue;
      seenIds.add(key);
      rules.push(entry);
    }
  }
  const adderLines = rules.map(({ rule, selector }) => {
    const comment = rule.comment
      ? `\t-- ${rule.comment}\n`
      : "";
    return `${comment}\ta(${emitString(selector)}, ${emitCssProps(rule.props)})`;
  });

  // Palette du jeu : déclarée comme dans le vanilla, seulement si utilisée.
  const usesPalette = rules.some(({ rule }) => Object.values(rule.props).some(isPaletteColor));

  const content = [
    `-- Generated by TFUI - Transport Fever 3 UI Editor — fichier régénéré, ne pas modifier`,
    `local ssu = require "::/gui/main/stylesheetutil.lua"`,
    `function data()`,
    `\tlocal result = {}`,
    `\tlocal a = ssu.makeAdder(result)`,
    ...(usesPalette ? [`\tlocal colorDefault = ${PALETTE_ACCESS}`] : []),
    ...(adderLines.length > 0 ? adderLines : [`\t-- aucune règle`]),
    `\treturn result`,
    `end`,
    ``,
  ].join("\n");

  return {
    path: `${fileBase}.css.lua`,
    content,
    sourceMap: [],
    kind: "css",
    screenId: screens[0]?.id,
  };
}
